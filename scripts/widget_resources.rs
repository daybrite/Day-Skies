//! Native widget accessors generated from the same Fluent catalog as the app.
//! Widget messages deliberately have no arguments; Foundation formats numbers/dates.
use std::{collections::BTreeMap, fs, path::Path};

pub fn generate() {
    println!("cargo:rerun-if-changed=scripts/widget_resources.rs");
    let root = Path::new("platform/ios/WeatherWidget");
    let catalogs = Path::new("resource/locales");
    let mut expected = None;
    let mut locales: Vec<_> = fs::read_dir(catalogs)
        .expect("resource/locales is a readable directory")
        .map(|p| p.expect("read a resource/locales entry").path())
        .collect();
    locales.sort();
    for locale in locales {
        if !locale.is_dir() {
            continue;
        }
        let file = locale.join("app.ftl");
        println!("cargo:rerun-if-changed={}", file.display());
        let text = fs::read_to_string(file).expect("every locale directory has an app.ftl");
        let messages: BTreeMap<_, _> = text
            .lines()
            .filter_map(|line| {
                let (key, value) = line.split_once(" = ")?;
                (key.starts_with("widget_")
                    || key.starts_with("cond_")
                    || ["app_title", "weather_now", "data_mock"].contains(&key))
                .then_some((key, value))
            })
            .collect();
        let keys: Vec<_> = messages.keys().map(|key| key.to_string()).collect();
        if let Some(ref expected) = expected {
            assert_eq!(&keys, expected, "Widget translations differ");
        } else {
            expected = Some(keys);
        }
        let mut strings = String::from("/* Generated from resource/locales; do not edit. */\n");
        let display_name = messages["app_title"].to_string();
        for (key, value) in messages {
            assert!(
                !value.contains(['{', '}']),
                "Widget message {key} must be a simple string"
            );
            strings.push_str(&format!(
                "{} = {};\n",
                strings_literal(key),
                strings_literal(value)
            ));
        }
        let dir = root.join("Resources").join(format!(
            "{}.lproj",
            locale
                .file_name()
                .and_then(|name| name.to_str())
                .expect("a locale directory has a UTF-8 name")
        ));
        write_changed(&dir.join("Localizable.strings"), &strings);
        write_changed(
            &dir.join("InfoPlist.strings"),
            &format!(
                "/* Generated from resource/locales; do not edit. */\n\"CFBundleDisplayName\" = {};\n",
                strings_literal(&display_name)
            ),
        );
    }
    let mut swift = String::from(
        "// Generated by scripts/widget_resources.rs. Do not edit.\nimport Foundation\n\nenum WidgetStrings {\n",
    );
    for key in expected.expect("resource/locales has at least one locale") {
        swift.push_str(&format!(
            "    static var {key}: LocalizedStringResource {{ \"{key}\" }}\n"
        ));
    }
    swift.push_str("}\n");
    write_changed(&root.join("WidgetStrings.swift"), &swift);
    write_changed(
        &root.join("WidgetConfiguration.swift"),
        r#"// Generated by scripts/widget_resources.rs. Do not edit.
import AppIntents
import Foundation
// App Intents metadata extraction requires literals at the declaration site.
// Generate the declarations too, so all UI keys still come from this resource generator.
struct CityEntity: AppEntity {
    static let typeDisplayRepresentation = TypeDisplayRepresentation(name: "widget_city")
    static var defaultQuery: CityQuery { CityQuery() }
    let id: String
    let name: String
    var displayRepresentation: DisplayRepresentation { DisplayRepresentation(title: "\(name)") }
}

struct SelectCity: WidgetConfigurationIntent {
    static let title: LocalizedStringResource = "widget_title"
    @Parameter(title: "widget_city") var city: CityEntity?
}
"#,
    );
}

// Rust Debug escapes combining marks as `\u{...}`, which is not .strings syntax.
// Preserve UTF-8, including Arabic diacritics, and escape only the file syntax.
fn strings_literal(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', "\\n")
            .replace('\r', "\\r")
            .replace('\t', "\\t")
    )
}

fn write_changed(path: &Path, value: &str) {
    if fs::read_to_string(path).ok().as_deref() == Some(value) {
        return;
    }
    let dir = path
        .parent()
        .expect("generated files are written under the widget directory");
    fs::create_dir_all(dir).expect("create the generated file's directory");
    fs::write(path, value).expect("write the generated file");
}
